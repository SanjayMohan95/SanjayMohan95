import type { Order } from '@/types';
import { formatLongDate, formatMoney, formatTime } from './format';

const esc = (s: string) => s.replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]!);

/** Renders a printable, self-contained VAT invoice (HTML) for an order. */
export function renderVatInvoice(order: Order): string {
  const b = order.breakdown;
  const vatable = b.total - b.tip;
  const net = vatable - b.vatIncluded;
  const rows = order.items
    .map(
      (i) => `<tr><td>${i.quantity}</td><td>${esc(i.name)}${i.modifiers.length ? `<div class="mod">${esc(i.modifiers.map((m) => m.optionName).join(', '))}</div>` : ''}<div class="mod">${esc(i.restaurantName)}</div></td><td class="r">${formatMoney(i.unitPrice)}</td><td class="r">${formatMoney(i.unitPrice * i.quantity)}</td></tr>`,
    )
    .join('');
  const feeRow = (label: string, v: number, neg = false) => (v ? `<tr><td colspan="3">${label}</td><td class="r">${neg ? '−' : ''}${formatMoney(v)}</td></tr>` : '');

  return `<!doctype html><html lang="en-GB"><head><meta charset="utf-8"><title>VAT invoice ${order.vatInvoiceNumber}</title>
<style>
body{font:14px/1.5 -apple-system,Segoe UI,Roboto,sans-serif;color:#141519;max-width:760px;margin:40px auto;padding:0 24px}
h1{font-size:22px;margin:0}.muted{color:#4a4d57}table{width:100%;border-collapse:collapse;margin-top:24px}
th,td{padding:8px 6px;border-bottom:1px solid #e2e3e6;text-align:left;vertical-align:top}.r{text-align:right}
.mod{font-size:12px;color:#4a4d57}.tot td{font-weight:700;border-top:2px solid #141519}.grid{display:flex;justify-content:space-between;gap:24px;margin-top:24px}
.brand{color:#a12506;font-weight:800}@media print{body{margin:0}}
</style></head><body>
<div class="grid"><div><h1><span class="brand">CraveOS</span> — VAT invoice</h1><p class="muted">CraveOS Ltd (demo entity) · 1 Example Yard, London EC1A 1BB<br>VAT registration: GB 000 0000 00 (illustrative)</p></div>
<div class="r"><strong>${order.vatInvoiceNumber}</strong><br><span class="muted">Order ${order.shortCode}</span><br><span class="muted">${formatLongDate(order.createdAt)}, ${formatTime(order.createdAt)}</span></div></div>
<div class="grid"><div><strong>Billed to</strong><br>${esc(order.contact.fullName)}<br>${esc([order.address.line2, order.address.line1].filter(Boolean).join(', '))}<br>${esc(order.address.city)} ${esc(order.address.postcode)}</div>
<div class="r"><strong>Supplied by</strong><br>${order.restaurants.map((r) => `${esc(r.name)}<br><span class="muted">${esc(r.address)}</span>`).join('<br>')}</div></div>
<table><thead><tr><th>Qty</th><th>Item</th><th class="r">Unit</th><th class="r">Amount</th></tr></thead><tbody>${rows}
<tr><td colspan="3">Subtotal</td><td class="r">${formatMoney(b.subtotal)}</td></tr>
${feeRow('Delivery fee', b.deliveryFee)}${feeRow('Multi-drop fee', b.multiDropFee)}${feeRow('Small order fee', b.smallOrderFee)}${feeRow('Service fee', b.serviceFee)}
${feeRow(`Discount${order.promoCode ? ` (${esc(order.promoCode)})` : ''}`, b.discount, true)}
<tr><td colspan="3">Net amount (excl. VAT)</td><td class="r">${formatMoney(net)}</td></tr>
<tr><td colspan="3">VAT @ 20%</td><td class="r">${formatMoney(b.vatIncluded)}</td></tr>
${feeRow('Courier tip (outside the scope of VAT)', b.tip)}
<tr class="tot"><td colspan="3">Total paid</td><td class="r">${formatMoney(b.total)}</td></tr></tbody></table>
<p class="muted">Paid by ${esc(order.payment.label)}.${order.deliveredAt ? ` Delivered ${formatLongDate(order.deliveredAt)} at ${formatTime(order.deliveredAt)}.` : ''}</p>
<p class="muted" style="font-size:12px">This invoice was generated by a demonstration platform and is not a valid tax document.</p>
</body></html>`;
}

export function downloadVatInvoice(order: Order): void {
  const blob = new Blob([renderVatInvoice(order)], { type: 'text/html;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `${order.vatInvoiceNumber}.html`;
  document.body.appendChild(a);
  a.click();
  a.remove();
  window.setTimeout(() => URL.revokeObjectURL(url), 1000);
}

/** Invoice markup scoped for in-page display (inside a dialog). */
export function renderVatInvoiceFragment(order: Order): { css: string; html: string } {
  const doc = renderVatInvoice(order);
  const css = (doc.match(/<style>([\s\S]*?)<\/style>/)?.[1] ?? '')
    .replace('@media print{body{margin:0}}', '')
    .replace(/(^|})\s*body\{[^}]*\}/, '$1')
    .replace(/(^|})([^{}@]+)\{/g, (_m, close: string, sel: string) => `${close}${sel.split(',').map((x) => `.vat-invoice ${x.trim()}`).join(',')}{`);
  const html = doc.match(/<body>([\s\S]*)<\/body>/)?.[1] ?? '';
  return { css, html };
}
